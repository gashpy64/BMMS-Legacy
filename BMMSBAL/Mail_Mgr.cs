using System;
using System.Collections.Generic;
using System.Text;
using System.IO;
using System.Web;
using System.Data;
using System.Collections;
using System.Net;
using System.Net.Mail;

namespace BMMSBAL
{
    public class Mail_Mgr
    {      

        #region SendWebEmail
        public static string SendWebEmail(string ToMailId, string Subject, string BodyText, string AttachFileName, string Bcc)
        {

            string pSMTPServer = string.Empty;
            string pSMTPServerPort = string.Empty;
            string pUserName = string.Empty;
            string pPassword = string.Empty;

            try
            {
                DataTable dtSMTPMaster = Utilities.GetSMTPMaster();

                pSMTPServer = dtSMTPMaster.Rows[0]["SMTPServer"].ToString();
                pSMTPServerPort = dtSMTPMaster.Rows[0]["SMTPServerPort"].ToString();
                pUserName = dtSMTPMaster.Rows[0]["UserName"].ToString();
                pPassword = Common.UnprotectSecret(dtSMTPMaster.Rows[0]["Password"].ToString());

                string pFromMailId = dtSMTPMaster.Rows[0]["FromMailId"].ToString();

                string pBcc = dtSMTPMaster.Rows[0]["Bcc"].ToString();

                string pTo = string.Empty;

                string pSubject = string.Empty;

                pSubject = Subject;

                pTo = ToMailId;

                if (Bcc != null)
                    pBcc += ", " + Bcc;
                else
                    pBcc = Bcc;

                string pBody = BodyText;


                int smtpPort;
                if (!int.TryParse(pSMTPServerPort, out smtpPort))
                    smtpPort = 25;

                // using: releases the attachment file once the mail is sent
                using (MailMessage eMail = new MailMessage())
                {
                    eMail.From = new MailAddress(pFromMailId);
                    AddMailAddresses(eMail.To, pTo);

                    if (pBcc != null)
                        if (pBcc.Trim() != string.Empty)
                            AddMailAddresses(eMail.Bcc, pBcc);

                    // UTF-8 for the subject, the body and the headers (step U1b): the rupee sign and Tamil
                    // and Hindi letters arrive as typed in every mail program
                    eMail.SubjectEncoding = Encoding.UTF8;
                    eMail.BodyEncoding = Encoding.UTF8;
                    eMail.HeadersEncoding = Encoding.UTF8;

                    eMail.Subject = pSubject;

                    eMail.IsBodyHtml = true;
                    pBody += "<br /> <br /> <b>Note :</b> This alert is generated by ";
                    pBody += "<b>Board Minutes and Meeting Software</b> ";
                    pBody += "for your information. Please do not reply.";
                    eMail.Body = pBody;


                    if (AttachFileName != null)
                    {
                        // A file with a Tamil or Hindi name keeps its name (step U1b)
                        Attachment attachment = new Attachment(AttachFileName);
                        attachment.NameEncoding = Encoding.UTF8;
                        eMail.Attachments.Add(attachment);
                    }

                    using (SmtpClient smtp = new SmtpClient(pSMTPServer, smtpPort))
                    {
                        if (pUserName.Trim() != string.Empty)
                            smtp.Credentials = new NetworkCredential(pUserName, pPassword);

                        smtp.Send(eMail);
                    }
                }

                Common.SaveSendMail(ToMailId, Subject, BodyText, AttachFileName, int.Parse(HttpContext.Current.Session["UserId"].ToString()));

                return "Success";
            }
            catch (Exception ex)
            {
                string msg = string.Empty;
                //msg += "| SMTPServer = " + pSMTPServer + " | ";
                //msg += "| SMTPServerPort = " + pSMTPServerPort + " | ";
                //msg += "| UserName = " + pUserName + " | ";
                //msg += "| Password = " + pPassword + " | ";

                Utilities.WriteErrorLog("Mail_Mgr", "SendWebEmail", ex.ToString() + msg.ToString());
                return "Error: " + ex.Message.ToString();
            }
        }
        #endregion


        #region AddMailAddresses
        // Accepts addresses separated by comma or semicolon and skips blanks.
        private static void AddMailAddresses(MailAddressCollection addresses, string mailIds)
        {
            foreach (string mailId in mailIds.Split(new char[] { ',', ';' }))
            {
                if (mailId.Trim() != string.Empty)
                    addresses.Add(new MailAddress(mailId.Trim()));
            }
        }
        #endregion



    }
}
